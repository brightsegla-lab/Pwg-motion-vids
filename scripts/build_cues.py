"""Build <episode>/assets/js/data.js: named cues (from cues.spec.json + transcript),
speaker turns (speakers.json) and the per-frame loudness envelope (loudness.json),
as plain JS globals so the composition never fetches at render time.
Usage: python3 scripts/build_cues.py <episode_dir> <basename>
"""
import json, re, sys

ep, name = sys.argv[1], sys.argv[2]
spec = json.load(open(f"{ep}/cues.spec.json"))
tr = json.load(open(f"{ep}/assets/transcript/{name}.json"))
words = [(w["text"], w["start_time"]) for s in tr["segments"] for w in s["words"] if w["text"].strip() and not w["text"].startswith("[")]
norm = lambda t: re.sub(r"[^\wäöüß°-]", "", t.lower())
toks = [norm(w) for w, _ in words]

def find(phrase, after):
    q = [norm(x) for x in phrase.split()]
    for i in range(len(toks) - len(q) + 1):
        if words[i][1] >= after and all(toks[i + k].startswith(q[k]) for k in range(len(q))):
            return words[i][1]
    raise SystemExit(f"cue phrase not found: {phrase!r} after {after}")

lead = spec.get("lead", 0.2)
cues, spoken = {}, {}
for key, entry in spec["cues"].items():
    phrase, after, *rest = entry
    t = find(phrase, after)
    spoken[key] = {"phrase": phrase, "spoken": t}
    cues[key] = round(t - lead + (rest[0] if rest else 0), 3)

speakers = json.load(open(f"{ep}/speakers.json"))
turns = [[t["start"], t["end"], t["speaker"]] for t in speakers["turns"]]
loud = json.load(open(f"{ep}/loudness.json"))

js = ["// Generated by scripts/build_cues.py — do not edit by hand; edit cues.spec.json and rebuild.",
      f"window.CUES = {json.dumps(cues, separators=(',', ':'))};",
      f"window.CUE_SOURCE = {json.dumps(spoken, ensure_ascii=False, separators=(',', ':'))};",
      f"window.TURNS = {json.dumps(turns, separators=(',', ':'))};",
      f"window.LOUDNESS = {{fps:{loud['fps']},values:{json.dumps(loud['values'], separators=(',', ':'))}}};"]
open(f"{ep}/assets/js/data.js", "w").write("\n".join(js) + "\n")
print(len(cues), "cues ->", f"{ep}/assets/js/data.js")
